-- 0181_ai_desk_questions.sql
-- Private question history for the Commissioner Desk (commissioner-only page in Commissioner Settings). One row per question asked.
-- Holds the question and the answer card so the commissioner can reopen it, and the "Report a problem" note that becomes a private draft
-- eval case. Never read by owner-facing routes. Purged after 90 days by the desk handler (a bounded DELETE on created_at).
-- Isolated from league data on purpose: nothing here is read by a league transaction, roster, cap or contract path, and the desk writes
-- nowhere else. NOT applied anywhere: local databases only until Keith approves a production migration.
CREATE TABLE IF NOT EXISTS ai_desk_questions (
  id TEXT PRIMARY KEY,                      -- random id generated by the worker
  created_at INTEGER NOT NULL,              -- unix seconds
  asked_by TEXT NOT NULL,                   -- the proven commissioner franchise id (e.g. 0008), never a name
  question TEXT NOT NULL,
  as_of TEXT,                               -- the date the question was asked "as of" (YYYY-MM-DD or 'current')
  state TEXT NOT NULL,                      -- the card state
  card_json TEXT,                           -- the validated answer card
  cost_usd REAL NOT NULL DEFAULT 0,
  duration_ms INTEGER,
  tool_calls INTEGER NOT NULL DEFAULT 0,
  canon_sha TEXT,
  report_note TEXT,                         -- "Report a problem": the commissioner's own words
  reported_at INTEGER
);
CREATE INDEX IF NOT EXISTS idx_ai_desk_questions_created ON ai_desk_questions (created_at);
CREATE INDEX IF NOT EXISTS idx_ai_desk_questions_asker ON ai_desk_questions (asked_by, created_at);
