#!/usr/bin/env node
// Regenerates site/shared/trade_rules.js — the browser twin of worker/src/trade_rules.js — so the Trade War Room and the
// worker run the same trade arithmetic byte for byte (Trade Builder P1).
//
//   node scripts/generate_shared_trade_rules.mjs           rewrite site/shared/trade_rules.js
//   node scripts/generate_shared_trade_rules.mjs --check   exit 1 if it is out of date (writes nothing)
//
// Body = worker/src/trade_rules.js from its first `export` down, with `export ` removed and every line indented two
// spaces, between the "---- body: generated" and "---- end body ----" markers. tests/trade_rules.test.mjs checks the
// same thing. Bump the ?v= stamp of ../shared/trade_rules.js in site/trades/trade_workbench.html when the body changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "worker/src/trade_rules.js");
const OUT = path.join(ROOT, "site/shared/trade_rules.js");

export function sharedBody(workerSrc) {
  const start = workerSrc.search(/^export /m);
  if (start < 0) throw new Error("worker/src/trade_rules.js has no export");
  return workerSrc.slice(start).replace(/^export (const|function) /gm, "$1 ").trimEnd();
}

export function exportedNames(workerSrc) {
  return [...workerSrc.matchAll(/^export (?:const|function) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
}

export function render(workerSrc) {
  const body = sharedBody(workerSrc).split("\n").map((l) => (l ? "  " + l : l)).join("\n");
  const api = exportedNames(workerSrc).map((n) => `${n}: ${n}`).join(", ");
  return `/* UPS trade rules, browser twin of worker/src/trade_rules.js — the trade arithmetic the worker and the desktop
   Trade War Room share (Trade Builder P1). Same body, byte for byte (tests/trade_rules.test.mjs). GENERATED by
   \`node scripts/generate_shared_trade_rules.mjs\`; edit the worker module, never this file. Attaches
   window.UPS_TRADE_RULES (and module.exports under Node). */
(function (root) {
  "use strict";
  // ---- body: generated from worker/src/trade_rules.js (keep in step; the test fails otherwise) ----
${body}
  // ---- end body ----
  var api = { ${api} };
  root.UPS_TRADE_RULES = api;
  if (typeof module !== "undefined" && module.exports) module.exports = api;
})(typeof window !== "undefined" ? window : this);
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render(fs.readFileSync(SRC, "utf8"));
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (cur !== next) { console.error("site/shared/trade_rules.js is out of date: run node scripts/generate_shared_trade_rules.mjs"); process.exit(1); }
    console.log("site/shared/trade_rules.js is up to date");
  } else if (cur !== next) { fs.writeFileSync(OUT, next); console.log("wrote site/shared/trade_rules.js"); }
  else console.log("site/shared/trade_rules.js already up to date");
}
