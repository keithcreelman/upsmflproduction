// Regenerates worker/src/desk/data/rules_data.js from site/m/data/rules.json (which CI builds from docs/league_context_v1.md).
// The Worker cannot read site/ at run time, and a JSON import would depend on the bundler, so the desk bundles the same data as a plain JS module.
// It carries canon_digest (sha256 of the canon text, first 12 hex): at run time the desk hashes the canon text the Worker itself bundles and
// compares. A mismatch means this file is out of date; the desk then says so and declines rule answers (see knowledge staleness handling).
//   node scripts/ai_desk/build_rules_index.mjs          # write
//   node scripts/ai_desk/build_rules_index.mjs --check  # exit 1 if the module differs from rules.json (informational; not part of the safe suite)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const src = path.join(root, "site/m/data/rules.json");
const out = path.join(root, "worker/src/desk/data/rules_data.js");
const json = JSON.parse(fs.readFileSync(src, "utf8"));
const body = "// GENERATED by scripts/ai_desk/build_rules_index.mjs from site/m/data/rules.json. Do not edit by hand.\n"
  + `// canon_digest ${json.canon_digest} · canon_sha ${String(json.canon_sha).slice(0, 7)} · canon_date ${json.canon_date}\n`
  + "const RULES_DATA = " + JSON.stringify(json) + ";\nexport default RULES_DATA;\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== body) { console.error("rules_data.js is out of date with site/m/data/rules.json"); process.exit(1); }
  console.log("rules_data.js matches rules.json"); process.exit(0);
}
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(root, out)} (${body.length} bytes, canon_digest ${json.canon_digest})`);
